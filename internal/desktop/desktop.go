// Package desktop installs opt-in user application entries without changing defaults.
package desktop

import (
	"embed"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const marker = "# Generated by AppHolder\n"

//go:embed assets/hicolor/**
var iconAssets embed.FS

func quote(s string) string {
	s = strings.ReplaceAll(s, "%", "%%")
	return "\"" + strings.NewReplacer("\\", "\\\\", "\"", "\\\"", "`", "\\`", "$", "\\$").Replace(s) + "\""
}
func Install(dir, executable string) error {
	if !filepath.IsAbs(executable) || strings.ContainsAny(executable, "\r\n") {
		return fmt.Errorf("executable must be an absolute path without newlines")
	}
	entry := marker + fmt.Sprintf("[Desktop Entry]\nType=Application\nName=AppHolder AppImage Handler\nNoDisplay=true\nComment=A home for your AppImages\nExec=%s open %%f\nIcon=appholder\nTerminal=false\nCategories=Utility;\nMimeType=application/vnd.appimage;application/x-iso9660-appimage;\nActions=Library;\n\n[Desktop Action Library]\nName=Open library\nExec=%s gui\n", quote(executable), quote(executable))
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	library := marker + fmt.Sprintf("[Desktop Entry]\nType=Application\nName=AppHolder\nComment=A home for your AppImages\nExec=%s gui\nIcon=appholder\nTerminal=false\nCategories=Utility;\n", quote(executable))
	uri := marker + fmt.Sprintf("[Desktop Entry]\nType=Application\nName=AppHolder Link Handler\nNoDisplay=true\nExec=%s open-uri %%u\nIcon=appholder\nTerminal=false\nMimeType=x-scheme-handler/appimg;\n", quote(executable))
	entries := map[string]string{"appholder-uri.desktop": uri, "appholder-open.desktop": entry, "appholder.desktop": library}
	for name, text := range entries {
		path := filepath.Join(dir, name)
		if st, err := os.Lstat(path); err == nil && st.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("refusing to replace a desktop-entry symlink: %s", path)
		}
		existing, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if err == nil && string(existing) != text && !strings.HasPrefix(string(existing), marker) {
			return fmt.Errorf("refusing to overwrite an unrelated desktop entry: %s", path)
		}
	}
	if err := installIcons(filepath.Join(filepath.Dir(dir), "icons", "hicolor")); err != nil {
		return err
	}
	for name, text := range entries {
		path := filepath.Join(dir, name)
		existing, err := os.ReadFile(path)
		if err == nil && string(existing) == text {
			continue
		}
		file, err := os.CreateTemp(dir, ".appholder-desktop-*")
		if err != nil {
			return err
		}
		temp := file.Name()
		if _, err = file.WriteString(text); err != nil {
			file.Close()
			os.Remove(temp)
			return err
		}
		if err = file.Chmod(0644); err != nil {
			file.Close()
			os.Remove(temp)
			return err
		}
		if err = file.Close(); err != nil {
			os.Remove(temp)
			return err
		}
		if err = os.Rename(temp, path); err != nil {
			os.Remove(temp)
			return err
		}
	}
	return nil
}

func installIcons(root string) error {
	const embeddedRoot = "assets/hicolor"
	if err := fs.WalkDir(iconAssets, embeddedRoot, func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(embeddedRoot, filepath.FromSlash(name))
		if err != nil {
			return err
		}
		dest := filepath.Join(root, rel)
		if info, err := os.Lstat(dest); err == nil && (info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular()) {
			return fmt.Errorf("refusing to replace a non-regular icon file: %s", dest)
		} else if err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}); err != nil {
		return err
	}
	return fs.WalkDir(iconAssets, embeddedRoot, func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil || entry.IsDir() {
			return walkErr
		}
		rel, err := filepath.Rel(embeddedRoot, filepath.FromSlash(name))
		if err != nil {
			return err
		}
		dest := filepath.Join(root, rel)
		if err = os.MkdirAll(filepath.Dir(dest), 0755); err != nil {
			return err
		}
		data, err := iconAssets.ReadFile(name)
		if err != nil {
			return err
		}
		file, err := os.CreateTemp(filepath.Dir(dest), ".appholder-icon-*")
		if err != nil {
			return err
		}
		temp := file.Name()
		if _, err = file.Write(data); err != nil {
			file.Close()
			os.Remove(temp)
			return err
		}
		if err = file.Chmod(0644); err != nil {
			file.Close()
			os.Remove(temp)
			return err
		}
		if err = file.Close(); err != nil {
			os.Remove(temp)
			return err
		}
		if err = os.Rename(temp, dest); err != nil {
			os.Remove(temp)
			return err
		}
		return nil
	})
}
