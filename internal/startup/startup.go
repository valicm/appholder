// Package startup manages opt-in per-user daemon and desktop autostart entries.
package startup

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

const marker = "# Generated by AppHolder\n"

type Controller struct {
	ConfigDir, Executable string
	Run                   func(...string) error
}

func New() (*Controller, error) {
	if os.Geteuid() == 0 {
		return nil, fmt.Errorf("configure startup as your normal user, without sudo")
	}
	root := os.Getenv("XDG_CONFIG_HOME")
	if root == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return nil, err
		}
		root = filepath.Join(home, ".config")
	}
	executable, err := os.Executable()
	if err != nil {
		return nil, err
	}
	return &Controller{ConfigDir: root, Executable: executable, Run: systemctl}, nil
}
func systemctl(args ...string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	command := exec.CommandContext(ctx, "systemctl", append([]string{"--user"}, args...)...)
	output, err := command.CombinedOutput()
	if err != nil {
		return fmt.Errorf("systemctl --user %s: %s (%w)", strings.Join(args, " "), strings.TrimSpace(string(output)), err)
	}
	return nil
}
func (c *Controller) paths() (string, string) {
	return filepath.Join(c.ConfigDir, "systemd", "user", "appholder.service"), filepath.Join(c.ConfigDir, "autostart", "appholder.desktop")
}
func owned(path string) error {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !strings.HasPrefix(string(data), marker) {
		return fmt.Errorf("refusing to modify an existing startup file not generated by AppHolder: %s", path)
	}
	return nil
}
func write(path, text string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".appholder-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err = file.WriteString(text); err != nil {
		file.Close()
		return err
	}
	if err = file.Chmod(0644); err != nil {
		file.Close()
		return err
	}
	if err = file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}
func (c *Controller) Enable() error {
	if !filepath.IsAbs(c.Executable) || strings.ContainsAny(c.Executable, "\n\r\x00") {
		return fmt.Errorf("invalid executable path")
	}
	unit, desktop := c.paths()
	for _, p := range []string{unit, desktop} {
		if err := owned(p); err != nil {
			return err
		}
	}
	// systemd expands percent specifiers and dollar variables, even inside quotes.
	unitPath := strings.NewReplacer("\\", "\\\\", "\"", "\\\"", "%", "%%", "$", "$$").Replace(c.Executable)
	unitText := marker + fmt.Sprintf("[Unit]\nDescription=AppHolder AppImage manager\n\n[Service]\nType=simple\nExecStart=\"%s\" daemon\nRestart=on-failure\nRestartSec=5\n\n[Install]\nWantedBy=default.target\n", unitPath)
	desktopPath := strings.NewReplacer("\\", "\\\\", "\"", "\\\"", "`", "\\`", "$", "\\$", "%", "%%").Replace(c.Executable)
	desktopText := marker + fmt.Sprintf("[Desktop Entry]\nType=Application\nName=AppHolder\nComment=AppImage library and tray\nExec=\"%s\" tray\nIcon=appholder\nTerminal=false\n", desktopPath)
	if err := write(unit, unitText); err != nil {
		return err
	}
	if err := c.Run("daemon-reload"); err != nil {
		return err
	}
	if err := c.Run("enable", "appholder.service"); err != nil {
		return err
	}
	return write(desktop, desktopText)
}
func (c *Controller) Disable() error {
	_, desktop := c.paths()
	if err := owned(desktop); err != nil {
		return err
	}
	// Disable future launches; leave this session's daemon and tray running.
	if err := c.Run("disable", "appholder.service"); err != nil {
		return err
	}
	if err := os.Remove(desktop); err != nil && !os.IsNotExist(err) {
		return err
	}
	return nil
}
func (c *Controller) Enabled() bool {
	_, desktop := c.paths()
	data, err := os.ReadFile(desktop)
	return err == nil && strings.HasPrefix(string(data), marker) && c.Run("is-enabled", "--quiet", "appholder.service") == nil
}
func (c *Controller) Start() error { return c.Run("start", "appholder.service") }
