// Package uninstall removes AppHolder's own executable and generated desktop files.
package uninstall

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"appholder/internal/startup"
)

const desktopMarker = "# Generated by AppHolder\n"

type Paths struct {
	Executable, Config, State, Data string
}

func UserPaths() (Paths, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return Paths{}, err
	}
	config := os.Getenv("XDG_CONFIG_HOME")
	if config == "" {
		config = filepath.Join(home, ".config")
	}
	state := os.Getenv("XDG_STATE_HOME")
	if state == "" {
		state = filepath.Join(home, ".local", "state")
	}
	data := os.Getenv("XDG_DATA_HOME")
	if data == "" {
		data = filepath.Join(home, ".local", "share")
	}
	executable, err := os.Executable()
	if err != nil {
		return Paths{}, err
	}
	return Paths{Executable: executable, Config: filepath.Join(config, "appholder"), State: filepath.Join(state, "appholder"), Data: data}, nil
}

func Run(purge bool) error {
	paths, err := UserPaths()
	if err != nil {
		return err
	}
	if os.Geteuid() == 0 {
		return fmt.Errorf("run AppHolder uninstall as your normal user, without sudo")
	}
	if err := stopStartup(); err != nil {
		return err
	}
	if err := removeGenerated(filepath.Join(paths.Data, "applications"), []string{"appholder.desktop", "appholder-open.desktop", "appholder-uri.desktop"}); err != nil {
		return err
	}
	if err := removeGenerated(filepath.Join(paths.Data, "applications"), appEntries(filepath.Join(paths.Data, "applications"))); err != nil {
		return err
	}
	if err := removeIcons(filepath.Join(paths.Data, "icons", "hicolor")); err != nil {
		return err
	}
	if err := removeExecutable(paths.Executable); err != nil {
		return err
	}
	if purge {
		for _, path := range []string{paths.Config, paths.State} {
			if err := os.RemoveAll(path); err != nil {
				return fmt.Errorf("remove %s: %w", path, err)
			}
		}
		fmt.Println("AppHolder removed. Its AppImages were kept; settings, metadata, and saved versions were purged.")
	} else {
		fmt.Printf("AppHolder removed. AppImages and settings were kept. Saved versions remain in %s. Use --purge to delete AppHolder data.\n", paths.State)
	}
	return nil
}

func stopStartup() error {
	c, err := startup.New()
	if err != nil {
		return err
	}
	unit := filepath.Join(c.ConfigDir, "systemd", "user", "appholder.service")
	unitData, unitErr := os.ReadFile(unit)
	if unitErr == nil && strings.HasPrefix(string(unitData), desktopMarker) {
		if err := c.Run("disable", "--now", "appholder.service"); err != nil {
			return err
		}
	} else if unitErr != nil && !os.IsNotExist(unitErr) {
		return unitErr
	}
	if err := removeGenerated(filepath.Dir(unit), []string{filepath.Base(unit)}); err != nil {
		return err
	}
	desktop := filepath.Join(c.ConfigDir, "autostart", "appholder.desktop")
	return removeGenerated(filepath.Dir(desktop), []string{filepath.Base(desktop)})
}

func appEntries(dir string) []string {
	entries, _ := os.ReadDir(dir)
	var names []string
	for _, entry := range entries {
		name := entry.Name()
		if strings.HasPrefix(name, "appholder-") && strings.HasSuffix(name, ".desktop") && name != "appholder-open.desktop" && name != "appholder-uri.desktop" {
			names = append(names, name)
		}
	}
	return names
}

func removeGenerated(dir string, names []string) error {
	for _, name := range names {
		path := filepath.Join(dir, name)
		info, err := os.Lstat(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(data), desktopMarker) {
			continue
		}
		if err = os.Remove(path); err != nil {
			return err
		}
	}
	return nil
}

func removeIcons(root string) error {
	for _, size := range []string{"16x16", "24x24", "32x32", "48x48", "64x64", "128x128", "256x256", "scalable", "symbolic"} {
		dir := filepath.Join(root, size, "apps")
		for _, name := range []string{"appholder.png", "appholder.svg", "appholder-symbolic.svg"} {
			path := filepath.Join(dir, name)
			info, err := os.Lstat(path)
			if os.IsNotExist(err) {
				continue
			}
			if err != nil {
				return err
			}
			if info.Mode().IsRegular() {
				if err := os.Remove(path); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func removeExecutable(path string) error {
	err := os.Remove(path)
	if err == nil || os.IsNotExist(err) {
		return nil
	}
	if !os.IsPermission(err) {
		return err
	}
	command := exec.Command("sudo", "rm", "-f", "--", path)
	command.Stdin = os.Stdin
	output, sudoErr := command.CombinedOutput()
	if sudoErr != nil {
		return fmt.Errorf("remove installed binary (use sudo if prompted): %s: %w", strings.TrimSpace(string(output)), sudoErr)
	}
	return nil
}
